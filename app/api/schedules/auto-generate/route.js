import { NextResponse } from "next/server";
import { getServerSession } from "next-auth";
import { authOptions } from "../../auth/[...nextauth]/route";
import { getAppConfig, updateAppConfig } from "@/lib/config";
import {
  generateAllDepartmentsMonth,
  nextMonthPartsJakarta,
} from "@/lib/schedules/generatePola";
import { nowInJakarta } from "@/lib/schedules/dates";
import { isAutoGenerateRunComplete } from "@/lib/schedules/protection";

function authorized(req, session) {
  const secret = process.env.SCHEDULE_CRON_SECRET || process.env.CRON_SECRET;
  const header = req.headers.get("x-cron-secret");
  if (secret && header && header === secret) return true;
  return (
    session?.user?.role === "Admin" ||
    session?.user?.permissions?.includes("manage_schedules")
  );
}

/**
 * POST /api/schedules/auto-generate
 * Day/hour evaluated in Asia/Jakarta.
 * Always targets next month (`nextMonthPartsJakarta`), skips departments that already
 * have schedules (`skipIfExists: true` by default), and preserves manually edited cells.
 */
export async function POST(req) {
  try {
    const session = await getServerSession(authOptions);
    if (!authorized(req, session)) {
      return NextResponse.json({ error: "Forbidden" }, { status: 403 });
    }

    const body = await req.json().catch(() => ({}));
    const config = await getAppConfig();
    const force = !!body.force;
    const day = parseInt(config.scheduleAutoGenerateDay ?? 15, 10);
    const jakarta = nowInJakarta();

    if (!force) {
      if (config.scheduleAutoGenerateEnabled === false) {
        return NextResponse.json({ skipped: true, reason: "disabled", tz: "Asia/Jakarta" });
      }
      if (jakarta.day !== day) {
        return NextResponse.json({
          skipped: true,
          reason: `Jakarta day is ${jakarta.day}, configured day is ${day}`,
          jakarta,
        });
      }
      const hour = parseInt(config.scheduleAutoGenerateHour ?? 1, 10);
      if (jakarta.hour !== hour) {
        return NextResponse.json({
          skipped: true,
          reason: `Jakarta hour is ${jakarta.hour}, configured hour is ${hour}`,
          jakarta,
        });
      }
    }

    const target =
      body.year && body.month
        ? { year: parseInt(body.year, 10), month: parseInt(body.month, 10) }
        : nextMonthPartsJakarta();

    const key = `${target.year}-${String(target.month).padStart(2, "0")}`;
    if (!force && config.lastScheduleAutoGenerateKey === key) {
      return NextResponse.json({ skipped: true, reason: "already generated", key });
    }

    const skipIfExists = body.skipIfExists !== undefined ? !!body.skipIfExists : true;
    const overwriteMode = body.overwriteMode === "force_all" ? "force_all" : "preserve_manual";

    const results = await generateAllDepartmentsMonth({
      year: target.year,
      month: target.month,
      skipIfExists,
      overwriteMode,
    });

    const recorded = isAutoGenerateRunComplete(results);
    const report = {
      key,
      ranAt: new Date().toISOString(),
      trigger: force ? "manual_next_month" : "cron_auto",
      target,
      recordedLastKey: recorded,
      results: results.map((r) => ({
        departmentId: r.departmentId,
        department: r.department,
        ok: r.ok !== false,
        pola: r.pola || null,
        count: r.count || 0,
        preservedCount: r.preservedCount || 0,
        skipped: !!r.skipped,
        reason: r.reason || null,
        error: r.error || null,
      })),
    };

    const configPatch = { lastScheduleAutoGenerateReport: report };
    if (recorded) {
      configPatch.lastScheduleAutoGenerateKey = key;
    }
    await updateAppConfig(configPatch);

    return NextResponse.json({
      success: recorded,
      partial: !recorded && results.some((r) => r.ok),
      recordedLastKey: recorded,
      target,
      key,
      jakarta,
      results,
      report,
      ...(!recorded
        ? { warning: "Sebagian departemen gagal; departemen yang sudah berhasil otomatis di-skip pada percobaan ulang." }
        : {}),
    });
  } catch (error) {
    return NextResponse.json({ error: error.message }, { status: 500 });
  }
}

export async function GET(req) {
  const session = await getServerSession(authOptions);
  if (!authorized(req, session)) {
    return NextResponse.json({ error: "Forbidden" }, { status: 403 });
  }
  const config = await getAppConfig();
  return NextResponse.json({
    enabled: config.scheduleAutoGenerateEnabled !== false,
    day: config.scheduleAutoGenerateDay ?? 15,
    hour: config.scheduleAutoGenerateHour ?? 1,
    lastKey: config.lastScheduleAutoGenerateKey || null,
    lastReport: config.lastScheduleAutoGenerateReport || null,
    nextTarget: nextMonthPartsJakarta(),
    jakarta: nowInJakarta(),
    tz: "Asia/Jakarta",
  });
}
